"""Postgres DDL rendered from `data/contract.py` (PLAN 4).

`tables()` runs before the COPY (PKs only, so the load is fast); `constraints()` and
`indexes()` run after it. Every statement is idempotent: re-running the load phases on an
existing schema is a no-op.
"""

from retail_pricing.data.contract import TABLES, Column, primary_key

APPLY_SCHEMA = "pricing_apply"
SCHEMAS = (*dict.fromkeys(t.split(".")[0] for t in TABLES), APPLY_SCHEMA)

# Defaults only for the columns the database maintains; seed rows carry their own values.
DEFAULTS = {
    "version": "1",
    "updated_at": "now()",
    "updated_by": "coalesce(nullif(current_setting('app.actor', true), ''), 'unknown')",
}

# Unique and check constraints the contract cannot express (PLAN 4 key tables).
UNIQUE_INDEXES = {
    "master_product_code_key": "master.product (product_code)",
    "master_store_code_key": "master.store (store_code)",
    "pricing_store_price_override_open_key": (
        "pricing.store_price_override (store_id, product_id) WHERE valid_to IS NULL"
    ),
    "pricing_shelf_label_queue_cycle_key": "pricing.shelf_label_queue (cycle_id, store_id, product_id)",
    "pricing_price_change_cycle_key": (
        "pricing.price_change (cycle_id, target, product_id, zone_id, store_id, promo_id)"
        " NULLS NOT DISTINCT"
    ),
}
CHECKS = {
    "pricing.zone_price": ("zone_price_price_check", "price > 0"),
    "ops.business_clock": ("business_clock_id_check", "id = 1"),
    "pricing.shelf_label_queue": (
        "shelf_label_queue_status_check",
        "status IN ('queued', 'printed')",
    ),
}
EXTRA_INDEXES = {
    "inventory.stock_movement": ("store_id", "product_id", "business_date"),
    "pricing.price_history": ("product_id", "zone_id", "valid_from"),
    "sales.sale": ("business_date",),
}


def _ident(table: str) -> str:
    return table.replace(".", "_")


def identity_column(table: str) -> str | None:
    """The single, non-FK PK column that gets an identity (business_clock is a fixed row)."""
    pk = [c for c in TABLES[table] if c.pk]
    if len(pk) == 1 and pk[0].fk is None and table != "ops.business_clock":
        return pk[0].name
    return None


def _column(table: str, c: Column) -> str:
    out = f"{c.name} {c.type}"
    if c.name == identity_column(table):
        out += " GENERATED BY DEFAULT AS IDENTITY"
    if not c.nullable:
        out += " NOT NULL"
    if c.name in DEFAULTS:
        out += f" DEFAULT {DEFAULTS[c.name]}"
    return out


def tables() -> list[str]:
    stmts = [f"CREATE SCHEMA IF NOT EXISTS {s}" for s in SCHEMAS]
    for table, cols in TABLES.items():
        body = [_column(table, c) for c in cols]
        body.append(f"PRIMARY KEY ({', '.join(primary_key(table))})")
        stmts.append(f"CREATE TABLE IF NOT EXISTS {table} (\n    " + ",\n    ".join(body) + "\n)")
    return stmts


def _add_constraint(table: str, name: str, definition: str) -> str:
    # ADD CONSTRAINT has no IF NOT EXISTS; swallow only the "already exists" error.
    return (
        f"DO $$ BEGIN ALTER TABLE {table} ADD CONSTRAINT {name} {definition}; "
        "EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL; END $$"
    )


def foreign_keys() -> list[tuple[str, str, str]]:
    """(table, column, "schema.table.column") for every FK in the contract."""
    return [(t, c.name, c.fk) for t, cols in TABLES.items() for c in cols if c.fk]


def constraints() -> list[str]:
    stmts = []
    for table, col, ref in foreign_keys():
        ref_table, ref_col = ref.rsplit(".", 1)
        stmts.append(
            _add_constraint(
                table,
                f"{_ident(table)}_{col}_fkey",
                f"FOREIGN KEY ({col}) REFERENCES {ref_table} ({ref_col})",
            )
        )
    for table, (name, expr) in CHECKS.items():
        stmts.append(_add_constraint(table, name, f"CHECK ({expr})"))
    stmts += [f"CREATE UNIQUE INDEX IF NOT EXISTS {n} ON {d}" for n, d in UNIQUE_INDEXES.items()]
    return stmts


def indexes() -> list[str]:
    """`updated_at` on every table, every FK column not leading the PK, and PLAN 4 extras."""
    stmts = [
        f"CREATE INDEX IF NOT EXISTS {_ident(t)}_updated_at_idx ON {t} (updated_at)" for t in TABLES
    ]
    for table, col, _ in foreign_keys():
        if primary_key(table)[0] != col:
            stmts.append(f"CREATE INDEX IF NOT EXISTS {_ident(table)}_{col}_idx ON {table} ({col})")
    for table, cols in EXTRA_INDEXES.items():
        name = f"{_ident(table)}_{'_'.join(cols)}_idx"
        stmts.append(f"CREATE INDEX IF NOT EXISTS {name} ON {table} ({', '.join(cols)})")
    return stmts
